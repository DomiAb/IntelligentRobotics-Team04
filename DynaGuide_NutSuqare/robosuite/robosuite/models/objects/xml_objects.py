class TightSquareNutObject(MujocoXMLObject):
    """
    Square nut with a configurable inner hole size for tight-fit insertion experiments.

    hole_x, hole_y: inner hole half-extents in metres (default 0.018 each → 36 mm hole,
    ~2 mm clearance per side vs. the 32 mm peg).  The original nut uses ~0.02275 (6.75 mm
    clearance).  Reducing these values makes insertion progressively harder.

    Wall thickness is kept constant at 0.0105 m to preserve the nut's outer shape and mass.
    """

    _WALL_THICK = 0.0105

    def __init__(self, name, hole_x=0.018, hole_y=0.018):
        self._hole_x = float(hole_x)
        self._hole_y = float(hole_y)
        super().__init__(
            xml_path_completion("objects/square-nut.xml"),
            name=name,
            joints=[dict(type="free", damping="0.0005")],
            obj_type="all",
            duplicate_collision_geoms=True,
        )

    def _get_object_subtree(self):
        # Modify wall geom positions and sizes before the base class parses the tree.
        hx, hy, wt = self._hole_x, self._hole_y, self._WALL_THICK
        geoms = self.worldbody.findall(".//body[@name='object']/geom")
        for geom in geoms:
            pos = [float(v) for v in geom.get("pos").split()]
            sz  = [float(v) for v in geom.get("size").split()]
            # Left / right walls: significant x-offset, y-offset near zero, not the handle
            if abs(pos[0]) > 0.01 and abs(pos[0]) < 0.05 and abs(pos[1]) < 0.01:
                sign = 1.0 if pos[0] > 0 else -1.0
                geom.set("pos",  f"{sign * (hx + wt):.6f} 0 0")
                geom.set("size", f"{wt} {hy + 2 * wt:.6f} {sz[2]}")
            # Front / back walls: significant y-offset, x-offset near zero
            elif abs(pos[1]) > 0.01 and abs(pos[0]) < 0.01:
                sign = 1.0 if pos[1] > 0 else -1.0
                geom.set("pos",  f"0 {sign * (hy + wt):.6f} 0")
                geom.set("size", f"{hx:.6f} {wt} {sz[2]}")
            # Handle geom (pos[0] > 0.04): left unchanged
        return super()._get_object_subtree()

    @property
    def important_sites(self):
        dic = super().important_sites
        dic.update({"handle": self.naming_prefix + "handle_site"})
        return dic


